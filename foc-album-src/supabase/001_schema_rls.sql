create or replace function public.foc2026_upsert_collection(
  p_username text,
  p_sticker_id text,
  p_source text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.foc2026_collections(player_username, sticker_id, quantity, source, is_new, updated_at)
  values (p_username, p_sticker_id, 1, p_source, true, now())
  on conflict (player_username, sticker_id)
  do update set
    quantity = foc2026_collections.quantity + 1,
    source = excluded.source,
    is_new = true,
    updated_at = now();
end;
$$;

create or replace function public.foc2026_open_pack(
  p_sticker_ids text[],
  p_pack_type text,
  p_round_number int
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username text := public.foc2026_current_username();
  v_player_name text;
  v_sticker text;
begin
  if v_username is null then
    raise exception 'not authenticated';
  end if;

  select name into v_player_name from public.foc2026_players where username = v_username;

  if p_pack_type = 'crest' and not public.foc2026_is_admin() then
    raise exception 'crest packs are disabled for players';
  end if;

  if p_pack_type = 'player' then
    update public.foc2026_players set pack_opened = true where username = v_username;
  end if;

  foreach v_sticker in array p_sticker_ids loop
    perform public.foc2026_upsert_collection(v_username, v_sticker, 'pack');
    insert into public.foc2026_stickers_log(player_username, round_number, message, type)
    values (
      v_username,
      p_round_number,
      coalesce(v_player_name, v_username) || ' obteve a figurinha ' || v_sticker || ' via ' ||
        case when p_pack_type = 'crest' then 'Pacotinho dourado' else 'Pacotinho inicial' end,
      'pack'
    );
  end loop;
end;
$$;

create or replace function public.foc2026_submit_houses(
  p_match_id text,
  p_houses text[]
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username text := public.foc2026_current_username();
  v_match public.foc2026_matches%rowtype;
begin
  if array_length(p_houses, 1) <> 3 then
    raise exception 'exactly 3 houses required';
  end if;

  select * into v_match from public.foc2026_matches where id = p_match_id;
  if not found or v_username not in (v_match.player_a_username, v_match.player_b_username) then
    raise exception 'match not found for user';
  end if;

  if v_username = v_match.player_a_username then
    update public.foc2026_matches set player_a_houses = array_to_string(p_houses, ',') where id = p_match_id;
  else
    update public.foc2026_matches set player_b_houses = array_to_string(p_houses, ',') where id = p_match_id;
  end if;
end;
$$;

create or replace function public.foc2026_report_own_keys(
  p_match_id text,
  p_keys int
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username text := public.foc2026_current_username();
  v_match public.foc2026_matches%rowtype;
begin
  if p_keys < 0 or p_keys > 3 then
    raise exception 'keys must be between 0 and 3';
  end if;

  select * into v_match from public.foc2026_matches where id = p_match_id for update;
  if not found or v_username not in (v_match.player_a_username, v_match.player_b_username) then
    raise exception 'match not found for user';
  end if;

  if v_username = v_match.player_a_username then
    update public.foc2026_matches
    set player_a_keys = p_keys,
        player_a_reported = true,
        player_a_picks_completed = false,
        completed = false
    where id = p_match_id;
  else
    update public.foc2026_matches
    set player_b_keys = p_keys,
        player_b_reported = true,
        player_b_picks_completed = false,
        completed = false
    where id = p_match_id;
  end if;

  update public.foc2026_matches
  set confirmed_at = now()
  where id = p_match_id
    and player_a_reported = true
    and player_b_reported = true
    and confirmed_at is null;
end;
$$;

create or replace function public.foc2026_reopen_own_report(p_match_id text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username text := public.foc2026_current_username();
  v_match public.foc2026_matches%rowtype;
begin
  select * into v_match from public.foc2026_matches where id = p_match_id for update;
  if not found or v_username not in (v_match.player_a_username, v_match.player_b_username) then
    raise exception 'match not found for user';
  end if;
  if v_match.completed then
    raise exception 'completed match cannot be reopened';
  end if;

  if v_username = v_match.player_a_username then
    update public.foc2026_matches
    set player_a_reported = false,
        player_a_picks_completed = false,
        confirmed_at = null,
        completed = false
    where id = p_match_id;
  else
    update public.foc2026_matches
    set player_b_reported = false,
        player_b_picks_completed = false,
        confirmed_at = null,
        completed = false
    where id = p_match_id;
  end if;
end;
$$;

create or replace function public.foc2026_claim_picks(
  p_match_id text,
  p_sticker_ids text[],
  p_round_number int
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username text := public.foc2026_current_username();
  v_player_name text;
  v_match public.foc2026_matches%rowtype;
  v_sticker text;
begin
  select * into v_match from public.foc2026_matches where id = p_match_id for update;
  if not found or v_username not in (v_match.player_a_username, v_match.player_b_username) then
    raise exception 'match not found for user';
  end if;
  if not (v_match.player_a_reported and v_match.player_b_reported) then
    raise exception 'picks are locked until both reports are submitted';
  end if;

  select name into v_player_name from public.foc2026_players where username = v_username;

  foreach v_sticker in array p_sticker_ids loop
    perform public.foc2026_upsert_collection(v_username, v_sticker, 'pick');
    insert into public.foc2026_stickers_log(player_username, round_number, message, type)
    values (
      v_username,
      p_round_number,
      coalesce(v_player_name, v_username) || ' obteve a figurinha ' || v_sticker || ' via Pick pós-partida',
      'pick'
    );
  end loop;

  if v_username = v_match.player_a_username then
    update public.foc2026_matches set player_a_picks_completed = true where id = p_match_id;
  else
    update public.foc2026_matches set player_b_picks_completed = true where id = p_match_id;
  end if;

  update public.foc2026_matches
  set completed = true
  where id = p_match_id
    and player_a_picks_completed = true
    and player_b_picks_completed = true;
end;
$$;

