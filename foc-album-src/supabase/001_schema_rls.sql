create extension if not exists pgcrypto;

create or replace function public.foc2026_current_username()
returns text
language sql
stable
as $$
  select coalesce(
    nullif(auth.jwt() -> 'user_metadata' ->> 'username', ''),
    nullif(auth.jwt() ->> 'email', '')
  )
$$;

create table if not exists public.foc2026_players (
  username text primary key,
  name text not null,
  is_admin boolean not null default false,
  pack_opened boolean not null default false,
  created_at timestamptz not null default now(),
  serie text
);

create table if not exists public.foc2026_rounds (
  number int primary key,
  name text not null,
  starts_at timestamptz,
  deadline timestamptz,
  sas_limit int,
  active boolean not null default false
);

create table if not exists public.foc2026_matches (
  id text primary key,
  round_number int not null references public.foc2026_rounds(number) on delete cascade,
  player_a_username text not null references public.foc2026_players(username),
  player_b_username text not null references public.foc2026_players(username),
  player_a_houses text,
  player_b_houses text,
  player_a_keys int not null default 0 check (player_a_keys between 0 and 3),
  player_b_keys int not null default 0 check (player_b_keys between 0 and 3),
  player_a_reported boolean not null default false,
  player_b_reported boolean not null default false,
  confirmed_at timestamptz,
  player_a_picks_completed boolean not null default false,
  player_b_picks_completed boolean not null default false,
  fallback_active boolean not null default false,
  match_deadline_passed boolean not null default false,
  completed boolean not null default false,
  check (player_a_username <> player_b_username)
);

create unique index if not exists foc2026_one_match_as_a_per_round
  on public.foc2026_matches(round_number, player_a_username);

create unique index if not exists foc2026_one_match_as_b_per_round
  on public.foc2026_matches(round_number, player_b_username);

create table if not exists public.foc2026_collections (
  player_username text not null references public.foc2026_players(username) on delete cascade,
  sticker_id text not null,
  quantity int not null default 1 check (quantity > 0),
  source text not null check (source in ('pack', 'pick', 'challenge', 'admin')),
  is_new boolean not null default true,
  updated_at timestamptz not null default now(),
  primary key (player_username, sticker_id)
);

create table if not exists public.foc2026_challenges (
  player_username text not null references public.foc2026_players(username) on delete cascade,
  id text not null,
  title text not null,
  description text not null,
  completed boolean not null default false,
  pending_validation boolean not null default false,
  picked_id text,
  primary key (player_username, id)
);

create table if not exists public.foc2026_admin_logs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  message text not null
);

create table if not exists public.foc2026_stickers_log (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  player_username text references public.foc2026_players(username),
  round_number int,
  message text not null,
  type text not null check (type in ('pack', 'pick', 'challenge', 'admin', 'info'))
);

create or replace function public.foc2026_is_admin()
returns boolean
language sql
stable
as $$
  select exists (
    select 1 from public.foc2026_players
    where username = public.foc2026_current_username()
      and is_admin = true
  )
$$;

